#!/usr/bin/env python3
"""Build the self-contained skill from the canonical standard, without network access."""

import ast
import hashlib
import json
import re
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo


ROOT = Path(__file__).resolve().parents[1]
SKILL = ROOT / "skills" / "simple-chinese"
CHAPTER_COUNTS = (7, 3, 3, 5, 5, 4, 2, 6, 7)


def require(condition, message):
    if not condition:
        raise ValueError(message)


def check_links(path, text, available, boundary):
    for target in re.findall(r"\[[^\]]*\]\(([^)\s]+)\)", text):
        if re.match(r"[a-zA-Z][a-zA-Z0-9+.-]*:", target) or target.startswith("#"):
            continue
        destination = (path.parent / target.split("#", 1)[0]).resolve()
        require(
            destination == boundary or boundary in destination.parents,
            f"Link outside content boundary in {path.relative_to(ROOT)}: {target}",
        )
        require(
            destination in available or (boundary == ROOT and destination.is_file()),
            f"Missing link in {path.relative_to(ROOT)}: {target}",
        )


def main():
    standard = (ROOT / "standard/plain-chinese-standard.md").read_text(encoding="utf-8")
    expected = [
        f"{chapter}.{rule}"
        for chapter, count in enumerate(CHAPTER_COUNTS, start=1)
        for rule in range(1, count + 1)
    ]
    actual = re.findall(r"^\| (\d+\.\d+) \|", standard, re.MULTILINE)
    require(actual == expected, "The standard must contain all 42 rules in order.")
    replies = re.findall(r"^\| (R\d+) \|", standard, re.MULTILINE)
    require(replies == [f"R{i}" for i in range(1, 7)], "Missing reply rules.")

    entry = (SKILL / "SKILL.md").read_text(encoding="utf-8")
    require(len(entry) < 3000, f"SKILL.md is too long: {len(entry)} characters.")
    require(entry.startswith("---\n"), "Missing skill frontmatter.")
    parts = entry.split("---\n", 2)
    require(len(parts) == 3, "Unclosed skill frontmatter.")
    require("name: simple-chinese" in parts[1].splitlines(), "Incorrect skill name.")
    require(
        re.search(r"^description: \S.+$", parts[1], re.MULTILINE),
        "Missing skill description.",
    )
    triggers = ("说人话", "简明中文", "白话", "去 AI 味", "写文档", "改成通俗的", "严格模式", "简明中文规范")
    require(all(word in parts[1] for word in triggers), "Missing Chinese trigger words.")
    version = re.search(r'^  version: "([0-9.]+)"$', parts[1], re.MULTILINE)
    require(version is not None, "Missing skill metadata version.")
    core = re.search(r"<!-- writing-rules:start -->\n(.*?)\n<!-- writing-rules:end -->", entry, re.S)
    require(core is not None, "Missing canonical writing rules.")
    prompt_path = ROOT / "prompts/system-prompt.md"
    prompt_source = prompt_path.read_text(encoding="utf-8")
    prompt, replacements = re.subn(
        r"<!-- full:start -->.*?<!-- full:end -->",
        lambda _: "<!-- full:start -->\n```text\n" + core.group(1).strip() + "\n```\n<!-- full:end -->",
        prompt_source, flags=re.S,
    )
    require(replacements == 1, "Expected one generated prompt region.")

    catalog = "<!-- Generated by scripts/build.py; edit standard/plain-chinese-standard.md. -->\n\n" + standard
    license_text = (ROOT / "LICENSE").read_text(encoding="utf-8")
    generated = {
        SKILL / "references/rule-catalog.md": catalog,
        SKILL / "LICENSE.txt": license_text,
    }
    package = {
        SKILL / "SKILL.md": entry,
        SKILL / "references/word-swaps.md": (SKILL / "references/word-swaps.md").read_text(encoding="utf-8"),
        SKILL / "references/use-cases.md": (SKILL / "references/use-cases.md").read_text(encoding="utf-8"),
        **generated,
    }
    documents = {
        ROOT / name: (ROOT / name).read_text(encoding="utf-8")
        for name in (
            "README.md",
            "standard/plain-chinese-standard.md",
            "prompts/system-prompt.md",
            "examples/before-after.md",
            "LICENSE",
        )
    }
    documents[prompt_path] = prompt
    available = set(documents) | set(package)
    for path, text in documents.items():
        check_links(path, text, available, ROOT)
    for path, text in package.items():
        check_links(path, text, set(package), SKILL)

    for path, text in generated.items():
        path.write_text(text, encoding="utf-8")
    prompt_path.write_text(prompt, encoding="utf-8")
    for path in list((ROOT / "evals").glob("*.py")) + list((ROOT / "tests").glob("*.py")):
        ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    for path in (ROOT / "evals").glob("*.json"):
        json.loads(path.read_text(encoding="utf-8"))
    output = ROOT / "dist"
    output.mkdir(exist_ok=True)
    archive = output / f"simple-chinese-v{version.group(1)}.zip"
    with ZipFile(archive, "w", compression=ZIP_DEFLATED) as bundle:
        for path, text in sorted(package.items()):
            name = "simple-chinese/" + path.relative_to(SKILL).as_posix()
            info = ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = ZIP_DEFLATED
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            bundle.writestr(info, text.encode("utf-8"))

    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    archive.with_suffix(".zip.sha256").write_text(
        f"{digest}  {archive.name}\n", encoding="utf-8"
    )
    print(f"Built {archive.relative_to(ROOT)} ({len(package)} files)")
    print(f"42 standard rules, 6 reply rules; SKILL.md: {len(entry)} characters")
    print(f"SHA-256: {digest}")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        raise SystemExit(f"Build failed: {error}")
